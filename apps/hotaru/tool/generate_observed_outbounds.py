from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1] / 'core/sing_box_host'
NODES = [
    ('Direct', 'direct', 'Direct'), ('HTTP', 'http', 'HTTP'),
    ('SOCKS', 'socks', 'SOCKS'), ('Shadowsocks', 'shadowsocks', 'Shadowsocks'),
    ('VMess', 'vmess', 'VMess'), ('VLESS', 'vless', 'VLESS'),
    ('Trojan', 'trojan', 'Trojan'), ('Hysteria2', 'hysteria2', 'Hysteria2'),
    ('TUIC', 'tuic', 'TUIC'),
]


def generate(name, nodes, constraint=''):
    parts = [constraint, '// Code generated by tool/generate_observed_outbounds.py; DO NOT EDIT.\npackage main\n\nimport (\n',
             '"context"\n"net"\n"github.com/sagernet/sing-box/adapter"\n"github.com/sagernet/sing-box/adapter/outbound"\n',
             'C "github.com/sagernet/sing-box/constant"\n"github.com/sagernet/sing-box/option"\n',
             'M "github.com/sagernet/sing/common/metadata"\n']
    for _, package, _ in nodes:
        parts.append(f'"github.com/sagernet/sing-box/protocol/{package}"\n')
    parts.append(')\n')
    parts.append(f'func {name}(registry *outbound.Registry, events *dialObservations) {{\n')
    for label, package, option in nodes:
        parts.append(f'''registerObserved[option.{option}OutboundOptions](registry, C.Type{label}, {package}.NewOutbound,
func(value adapter.Outbound) adapter.Outbound {{ return &observed{label}{{Outbound: value.(*{package}.Outbound), events: events}} }})\n''')
    parts.append('}\n')
    for label, package, _ in nodes:
        parts.append(f'''type observed{label} struct {{ *{package}.Outbound; events *dialObservations }}
func(h *observed{label}) Upstream() any {{ return h.Outbound }}
func(h *observed{label}) DialContext(ctx context.Context, network string, destination M.Socksaddr) (net.Conn, error) {{
 ctx, id := h.events.begin(ctx, h.Tag(), h.Type(), network, destination)
 connection, err := h.Outbound.DialContext(ctx, network, destination)
 h.events.end(id, err == nil)
 return connection, err
}}
func(h *observed{label}) ListenPacket(ctx context.Context, destination M.Socksaddr) (net.PacketConn, error) {{
 ctx, id := h.events.begin(ctx, h.Tag(), h.Type(), "udp", destination)
 connection, err := h.Outbound.ListenPacket(ctx, destination)
 h.events.end(id, err == nil)
 return connection, err
}}
''')
    (ROOT / f'{name}.go').write_text(''.join(parts))


generate('registerObservedOutbounds', NODES[:-2])
generate('registerObservedQUIC', NODES[-2:], '//go:build with_quic\n\n')
(ROOT / 'registerObservedQUIC_stub.go').write_text('''//go:build !with_quic

// Code generated by tool/generate_observed_outbounds.py; DO NOT EDIT.
package main
import "github.com/sagernet/sing-box/adapter/outbound"
func registerObservedQUIC(*outbound.Registry, *dialObservations) {}
''')

subprocess.run(['gofmt', '-w', *(str(ROOT / f'{name}.go') for name in [
    'registerObservedOutbounds', 'registerObservedQUIC', 'registerObservedQUIC_stub',
])], check=True)
